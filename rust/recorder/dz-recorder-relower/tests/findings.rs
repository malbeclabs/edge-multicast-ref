const TOB_PAYLOADS: [&str; 3] = [
    "q AAA 1000000001 99.50 12 100.50 7",
    "q AAA 1000000002 - - 100.75 3",
    "t AAA 1000000005 100.25 2 buy 7788",
];

fn quote(ts: u64, flags: u8, bid_price: i64, bid_qty: u64, ask_price: i64, ask_qty: u64) -> Quote {
    Quote {
        instrument_id: AAA.instrument_id,
        source_id: SOURCE_ID,
        update_flags: flags,
        source_timestamp_ns: ts,
        bid_price,
        bid_qty,
        ask_price,
        ask_qty,
        // Top-of-book says *unavailable* with zero, which is the opposite of the
        // depth feed's `0xFFFF`. Two specifications, one question, opposite
        // answers.
        bid_source_count: 0,
        ask_source_count: 0,
    }
}

fn tob_on_the_wire() -> Vec<Msg> {
    vec![
        Msg::Quote(quote(1_000_000_001, BOTH_UPDATED, 9_950, 12, 10_050, 7)),
        // A gone side is a zero price and a zero quantity, and the flag is what
        // says so: zero is an in-range price on the wire.
        Msg::Quote(quote(1_000_000_002, BID_GONE_ASK_UPDATED, 0, 0, 10_075, 3)),
        Msg::Trade(Trade {
            instrument_id: AAA.instrument_id,
            source_id: SOURCE_ID,
            aggressor_side: AGGRESSOR_BUY,
            trade_flags: 0,
            source_timestamp_ns: 1_000_000_005,
            trade_price: 10_025,
            trade_qty: 2,
            trade_id: 7788,
            cumulative_volume: 0,
        }),
    ]
}

fn tob_archive(messages: &[Msg], framing: Framing) -> DatagramLog {
    let mut archive = DatagramLog::new(refdata_datagrams::<TopOfBook>(&[AAA], 1));
    archive.extend(pack::<TopOfBook>(
        messages,
        dz_edge_core::PortRole::Mktdata,
        framing,
    ));
    archive
}

#[test]
fn a_top_of_book_window_that_agrees_produces_no_finding() {
    let mut archive = tob_archive(&tob_on_the_wire(), Framing::batched(3));
    archive.rotate(1);
    let mut adapter = LineAdapter::over(&[AAA]);
    let mut upstream = payloads(&TOB_PAYLOADS);

    let report = compare_archives(&mut adapter, &mut upstream, &mut archive, MAGIC_TOB)
        .expect("both archives are complete");

    assert!(report.is_clean(), "{:?}", report.findings);
    assert_eq!(report.summary.identical, 3);
}

#[test]
fn a_quote_joins_on_instrument_timestamp_and_update_flags() {
    // The design's own key for this feed, asserted as a key and not as a
    // behaviour: the second quote carries a gone bid, so its flags byte differs
    // from the first's, and the key says so.
    let mut wire = tob_on_the_wire();
    wire.remove(1);

    let mut archive = tob_archive(&wire, Framing::tight());
    let mut adapter = LineAdapter::over(&[AAA]);
    let mut upstream = payloads(&TOB_PAYLOADS);

    let report = compare_archives(&mut adapter, &mut upstream, &mut archive, MAGIC_TOB)
        .expect("both archives are complete");

    assert_eq!(report.findings.len(), 1, "{:?}", report.findings);
    assert_eq!(
        *report.findings[0].key(),
        JoinKey::TopOfBook {
            instrument_id: 11,
            source_timestamp_ns: 1_000_000_002,
            tie: TopOfBookTie::UpdateFlags(BID_GONE_ASK_UPDATED),
        }
    );
}

#[test]
fn a_quote_whose_gone_side_the_publisher_wrote_as_updated_is_two_findings_not_one() {
    // `Update Flags` is part of the top-of-book key, so a publisher that got the
    // byte wrong has not produced a differing copy of one message: it has
    // produced a message at a key the venue's events never reach. That is the
    // honest reading — the two copies are not the same message — and it is
    // stated here so that nobody reads the resulting pair of findings as a
    // defect in the join.
    let mut wire = tob_on_the_wire();
    wire[1] = Msg::Quote(quote(1_000_000_002, BOTH_UPDATED, 0, 0, 10_075, 3));

    let mut archive = tob_archive(&wire, Framing::tight());
    let mut adapter = LineAdapter::over(&[AAA]);
    let mut upstream = payloads(&TOB_PAYLOADS);

    let report = compare_archives(&mut adapter, &mut upstream, &mut archive, MAGIC_TOB)
        .expect("both archives are complete");

    assert_eq!(report.findings.len(), 2, "{:?}", report.findings);
    let outcomes: Vec<Outcome> = report
        .findings
        .iter()
        .map(dz_recorder_relower::Finding::outcome)
        .collect();
    assert!(outcomes.contains(&Outcome::OnWireNotReLowered));
    assert!(outcomes.contains(&Outcome::ReLoweredNotOnWire));
}
